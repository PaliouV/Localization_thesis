"""
Θόρυβος πυξίδας του «κόσμου» (15 Νοε 2026).

Το CARLA δίνει τέλεια πυξίδα (compass − 90° = αληθινό yaw, διαφορά < 0,02°). Εδώ της προσθέτουμε λάθος, όπως
το έχει η κατεύθυνση που δίνει μια μονάδα IMU με μαγνητόμετρο (AHRS) σε αυτοκίνητο μέσα στην πόλη.

Το λάθος:
  - αλλάζει ΑΡΓΑ (Gauss–Markov): μένει σχεδόν ίδιο για δεκάδες δευτερόλεπτα, δεν είναι καινούργιο σε κάθε μέτρηση
  - έχει το ΙΔΙΟ μέγεθος σε όλη την πόλη. Δεν ακολουθεί τις ζώνες του GPS: το GPS το χαλάνε τα ψηλά κτήρια,
    την πυξίδα τα μέταλλα και τα ρεύματα κοντά της (διπλανά αυτοκίνητα, σίδερα, καλώδια).

Από πού βγήκαν τα νούμερα:
  Μέγεθος (σ 9,8°): δικός μας υπολογισμός στο UrbanNav, αρχεία xsense_imu_*.csv, κατεύθυνση του Xsens απέναντι
    στο ground truth, 1 τιμή το δευτερόλεπτο, και οι τρεις διαδρομές μαζί (4635 s): RMS 9,81°.
    Συμφωνεί με μετρήσεις σκέτης πυξίδας σε αυτοκίνητο μέσα σε πόλη:
      Godha, Petovello & Lachapelle 2005 (ION GNSS), Πίνακας 6 σ. 10: RMS 8,5° (χωρίς αιχμές) έως 12,0°
      Cui κ.ά. 2024 (IEEE TIM 73, 9511914), Πίνακας VI σ. 12: μέσο απόλυτο λάθος 12,29°
  Διάρκεια (tau 130 s): ίδιος υπολογισμός. Ομοιότητα του λάθους με τον εαυτό του: 0,70 μετά από 60 s,
    0,30 μετά από 120 s. Το tau 130 s δίνει 0,63 και 0,40.
  Ότι το λάθος στην πόλη μένει για ώρα και δεν είναι τυχαίο κάθε στιγμή: Wu & Wang 2019 (J. Navigation 72),
    §2 σ. 1515–1516· Godha 2005 σ. 10.

ΠΑΡΑΔΟΧΕΣ:
  - Το σταθερό λάθος τοποθέτησης (−3° έως −7° στο UrbanNav) θεωρούμε ότι έχει αφαιρεθεί με βαθμονόμηση.
  - Απλό Gauss–Markov: από δευτερόλεπτο σε δευτερόλεπτο αλλάζει περισσότερο από το πραγματικό (≈1,2° αντί 0,25°).

Χρήση (μία κλήση το δευτερόλεπτο):
    compass = CompassNoise(seed=1, sigma=9.8, tau=130)
    measured_yaw = compass.step(true_yaw)      # rad
"""

import numpy as np


class CompassNoise:
    def __init__(self, seed=None, sigma=9.8, tau=130.0, dt=1.0):
        self.rng = np.random.default_rng(seed)
        self.sigma = np.radians(sigma)            # rad: τυπικό μέγεθος του λάθους
        self.keep = np.exp(-dt / tau)             # πόσο από το προηγούμενο λάθος μένει σε κάθε βήμα
        self.error = self.sigma * self.rng.normal()   # rad· ξεκινά από τυχαία, συνηθισμένη τιμή (όχι από 0)

    def step(self, true_yaw):
        """Η ένδειξη της πυξίδας (rad), όταν το αυτοκίνητο κοιτά στο true_yaw (rad)."""
        self.error = self.keep * self.error + np.sqrt(1 - self.keep ** 2) * self.sigma * self.rng.normal()
        return true_yaw + self.error


if __name__ == "__main__":
    # Γρήγορος έλεγχος: δέκα ώρες, να βγαίνει το σ και η ομοιότητα που ζητήσαμε.
    compass = CompassNoise(seed=0)
    errors = np.degrees([compass.step(0.0) for _ in range(36000)])
    print(f"σ {errors.std():.1f}°, ομοιότητα μετά από 60 s {np.corrcoef(errors[:-60], errors[60:])[0, 1]:.2f}, "
          f"μετά από 120 s {np.corrcoef(errors[:-120], errors[120:])[0, 1]:.2f}, αλλαγή σε 1 s {np.diff(errors).std():.2f}°")
